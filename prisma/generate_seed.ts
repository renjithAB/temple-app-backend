function escapeSql(str: string): string {
  return str.replace(/'/g, "''");
}

function generateUuid(prefix: string, index: number): string {
  // Deterministic UUID based on prefix and index:
  // e.g. 00000000-0000-4000-a000-000000000001
  const hex = (index + 1).toString(16).padStart(12, '0');
  const part = prefix.padStart(4, '0').slice(-4);
  return `00000000-0000-4000-${part}-${hex}`;
}

